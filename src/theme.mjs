/**
 * 국내판(`render.mjs`)과 영문판(`en.mjs`)이 **함께 쓰는 바닥.**
 *
 * ── 왜 뺐나 ────────────────────────────────────────────────
 * 두 파일이 CSS를 각자 갖고 있어서 한쪽만 고치면 조용히 갈라졌다. 실제로 갈라진 것들:
 *
 *   `--dim`          국내판만 #a0a0a0 → #8a8a8a (대비 2.6:1 → AA). 영문판은 남아 있었다
 *   폰트 크기        국내판 rem 89건 / px 0건, 영문판 px 11건 / rem 0건.
 *                    영문판은 브라우저 글자 크기 설정을 무시하고 있었다
 *   한글 폰트        국내판만 Malgun Gothic·Apple SD Gothic Neo를 선언한다.
 *                    **영문판도 한글을 그린다** — 특전 원문 줄(.ko)과 title 속성
 *   color-scheme     국내판에만 있었다
 *   포커스 링        손으로 옮겨서 맞췄다. 다음에 또 바꾸면 또 손으로 옮겨야 한다
 *
 * 로고(MARK)도 같은 이유로 두 번 갈라졌다가 `render.mjs`에서 export하는 것으로 끝냈다.
 * **베끼면 갈라진다.** 갈라지면 안 되는 것만 여기 둔다.
 *
 * ── 무엇을 넣지 않았나 ──────────────────────────────────────
 * 표·카드·헤더는 두 페이지가 **실제로 다르다.** 국내판 표는 가로 스크롤(min-width 640px)이
 * 필요하고 영문판은 네 칸뿐이다. 미디어쿼리 기준선도 700px / 640px로 다르다 —
 * 담는 내용이 다르니 갈라지는 게 맞다. 억지로 합치면 한쪽을 고칠 때마다 다른 쪽이 깨진다.
 *
 * 여기 있는 건 **둘이 같아야만 하는 것**뿐이다: 색 토큰, 상자 모델, 본문 타이포, 포커스 링.
 */

/**
 * 색 토큰.
 *
 * 무채 뼈대에 액센트 하나 — 화면의 절반이 앨범 커버라, 뼈대를 눌러두면 채도를 가진 건
 * 커버뿐이고 컴백마다 사이트 인상이 바뀐다. 근거는 `docs/38-조사-29cm.md`.
 *
 * `--acc`는 **경고에만** 쓴다(품절·마감). 긍정 상태는 색이 아니라 굵기로 낸다 —
 * 그래서 `--ok`가 초록이 아니라 먹이다. 액센트가 둘이면 어느 쪽도 안 급해 보인다.
 * (`--ok`는 지금 국내판만 쓰지만 토큰은 한 벌로 둔다. 둘로 나누면 또 갈라진다.)
 *
 * 다크모드는 두지 않는다. 커버가 화면의 색을 담당하는 구조라 바닥이 어두워지면
 * 그 전제가 흔들리고, 흰 배경 상품 사진이 검은 바닥 위의 흰 사각형이 된다.
 */
export const TOKENS =
  ':root{--bg:#fff;--fg:#1a1a1a;--mut:#757575;--dim:#8a8a8a;--line:#e4e4e4;--acc:#c2410c;--ok:#1a1a1a;--card:#f4f4f4}';

/**
 * 본문 타이포.
 *
 * **`px`가 아니라 `rem`이다.** `px`로 박으면 브라우저 글자 크기 설정을 무시한다 —
 * 확대해서 쓰는 사람에게 글자가 안 커진다(WCAG 1.4.4).
 *
 * 한글 폰트를 명시한다. 영문 페이지도 특전 원문을 한글로 보여주기 때문에
 * 여기가 비면 시스템 폴백에 맡기게 된다.
 *
 * 웹폰트는 안 쓴다. Pretendard를 얹었다가 걷어냈다 — 판매처에서 넘어오는 사람이
 * 많고, 첫 화면이 글자로 차 있어서 폰트 로딩이 그대로 체감된다.
 */
export const BODY =
  'body{margin:0 auto;padding:24px 24px 72px;max-width:880px;background:var(--bg);color:var(--fg);\n' +
  'font:1rem/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI","Malgun Gothic","Apple SD Gothic Neo",sans-serif}';

/**
 * 포커스 링.
 *
 * 리셋의 `outline:none` 하나 때문에 Tab으로 훑으면 지금 어디인지 알 수 없었다(WCAG 2.4.7).
 * 마우스에는 안 보이고 키보드에만 보이는 `:focus-visible`로 되살린다.
 * 페이지별 예외(카드가 투명 링크에 덮인 경우 등)는 각 파일에서 덧붙인다.
 */
export const FOCUS = ':focus-visible{outline:2px solid var(--fg);outline-offset:2px}';

/** 두 렌더러의 CSS 맨 앞에 그대로 붙인다. */
export const BASE_CSS = [TOKENS, 'html{color-scheme:light}', '*{box-sizing:border-box}', BODY, FOCUS].join('\n');
